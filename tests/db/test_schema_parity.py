"""The ORM metadata describes the migrated schema exactly [ARC-1].

**The migrations are the source of truth for what is deployed.**
``migrations/env.py`` gives Alembic :mod:`app.db.models` as its target, so
anything a migration created and the models omit is something a routine
``alembic revision --autogenerate`` writes a DROP for. Before this gate
that included the signup-draft and staging-outbox tables, the
token-revocation columns on ``refresh_token``, the seat-to-batch foreign
key and most of ``0030``'s indexes -- and in a solo build the person
reviewing that autogenerated migration is the person who generated it.

Two comparisons, because each sees what the other cannot:

* **``alembic check``**, run through ``migrations/env.py`` with the shared
  :data:`~app.db.schema_compare.COMPARE_OPTIONS`. This is the exact
  command a developer runs, so it is the one that must stay green.
* **The server's own catalogue, twice.** One database is migrated to head;
  a second is built from the models with ``create_all``. PostgreSQL then
  renders both: every column's type, nullability and default, every
  index definition, every primary-key, unique, foreign-key and CHECK
  constraint definition, and every enum's labels. This closes what
  Alembic does not compare -- a partial index's predicate, an expression
  index's uniqueness, a CHECK's expression or name, a foreign key's name
  or ``ON DELETE``, an enum's labels -- and it cannot be flaky over
  formatting, because the same server normalises both sides.

Deliberately NOT compared, because the models cannot express them and
their migrations own them alone: exclusion constraints (``0024``'s
overlap rules) and the indexes backing them, row-level-security policies,
triggers and their functions, grants, and extensions. Where they matter
they are exercised by the feature suites (``tests/privacy`` for the
policy, ``tests/payroll`` for the salary freeze, ``tests/scheduling``
for the overlap rules), not by this gate.

Each comparison is shown to fire, so a green run is evidence rather than
an absence of output.
"""

from __future__ import annotations

import uuid
from collections.abc import Iterator
from contextlib import contextmanager

import pytest
import sqlalchemy as sa
from alembic import command
from alembic.autogenerate import compare_metadata
from alembic.config import Config
from alembic.migration import MigrationContext
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy.dialects.postgresql import ENUM
from sqlalchemy.engine import Engine

from app.db import models as _models  # noqa: F401  registers the tables
from app.db.base import NAMING_CONVENTION, Base
from app.db.schema_compare import COMPARE_OPTIONS
from tests.db.migration_support import stage_at

#: ``kind -> {key: rendered definition}``, as PostgreSQL reports it.
Catalogue = dict[str, dict[tuple[str, ...], object]]

#: Columns: type, nullability and default, rendered by the server.
_COLUMNS = """
SELECT c.relname, a.attname,
       format_type(a.atttypid, a.atttypmod), a.attnotnull,
       pg_get_expr(d.adbin, d.adrelid)
FROM pg_attribute a
JOIN pg_class c ON c.oid = a.attrelid
JOIN pg_namespace n ON n.oid = c.relnamespace
LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
WHERE n.nspname = 'public' AND c.relkind = 'r'
  AND c.relname <> 'alembic_version'
  AND a.attnum > 0 AND NOT a.attisdropped
"""

#: Indexes, minus those backing an exclusion constraint (not modelled).
_INDEXES = """
SELECT t.relname, i.relname, pg_get_indexdef(i.oid)
FROM pg_index x
JOIN pg_class i ON i.oid = x.indexrelid
JOIN pg_class t ON t.oid = x.indrelid
JOIN pg_namespace n ON n.oid = t.relnamespace
WHERE n.nspname = 'public' AND t.relname <> 'alembic_version'
  AND NOT EXISTS (
      SELECT 1 FROM pg_constraint e
      WHERE e.contype = 'x' AND e.conindid = x.indexrelid
  )
"""

#: Primary-key, unique, foreign-key and CHECK constraints. Exclusion
#: constraints (``x``) are owned by ``0024`` alone.
_CONSTRAINTS = """
SELECT t.relname, c.conname, pg_get_constraintdef(c.oid)
FROM pg_constraint c
JOIN pg_class t ON t.oid = c.conrelid
JOIN pg_namespace n ON n.oid = t.relnamespace
WHERE n.nspname = 'public' AND t.relname <> 'alembic_version'
  AND c.contype IN ('p', 'u', 'f', 'c')
"""

#: Enum labels in declaration order.
_ENUMS = """
SELECT t.typname, string_agg(e.enumlabel, ',' ORDER BY e.enumsortorder)
FROM pg_enum e
JOIN pg_type t ON t.oid = e.enumtypid
JOIN pg_namespace n ON n.oid = t.typnamespace
WHERE n.nspname = 'public'
GROUP BY t.typname
"""


def _url(engine: Engine) -> str:
    """Render an engine's URL with its password, for Alembic.

    :param engine: The engine
    :return: The URL string
    """
    return engine.url.render_as_string(hide_password=False)


@contextmanager
def _built_from(postgres_url: str, metadata: sa.MetaData) -> Iterator[Engine]:
    """Create a throwaway database from a metadata, not from the migrations.

    The models declare every enum ``create_type=False``, because the
    migrations own the types' lifecycle; so each is created here first,
    from the labels the models spell.

    :param postgres_url: The owner connection URL of the container
    :param metadata: The metadata to build
    :return: A context manager yielding an engine on the new database
    """
    name = f"models_{uuid.uuid4().hex[:12]}"
    admin = sa.create_engine(postgres_url, isolation_level="AUTOCOMMIT")
    with admin.connect() as connection:
        connection.execute(sa.text(f'CREATE DATABASE "{name}"'))
    engine = sa.create_engine(
        sa.engine.make_url(postgres_url).set(database=name), poolclass=sa.pool.NullPool
    )
    try:
        with engine.begin() as connection:
            enums = {
                column.type.name: column.type
                for table in metadata.tables.values()
                for column in table.columns
                if isinstance(column.type, ENUM)
            }
            for enum in enums.values():
                enum.create(connection, checkfirst=False)
            metadata.create_all(connection)
        yield engine
    finally:
        engine.dispose()
        with admin.connect() as connection:
            connection.execute(sa.text(f'DROP DATABASE IF EXISTS "{name}"'))
        admin.dispose()


def _catalogue(engine: Engine) -> Catalogue:
    """Read what PostgreSQL says the schema is.

    :param engine: The database to read
    :return: Each kind of object, keyed by table and name
    """
    with engine.connect() as connection:
        return {
            "column": {
                (row[0], row[1]): tuple(row[2:])
                for row in connection.execute(sa.text(_COLUMNS))
            },
            "index": {
                (row[0], row[1]): row[2]
                for row in connection.execute(sa.text(_INDEXES))
            },
            "constraint": {
                (row[0], row[1]): row[2]
                for row in connection.execute(sa.text(_CONSTRAINTS))
            },
            "enum": {(row[0],): row[1] for row in connection.execute(sa.text(_ENUMS))},
        }


def _differences(migrated: Catalogue, modelled: Catalogue) -> list[str]:
    """List every object the two catalogues disagree on.

    :param migrated: The catalogue of the database migrated to head
    :param modelled: The catalogue of the database built from the models
    :return: One line per disagreement, empty when they agree
    """
    lines = []
    for kind, objects in migrated.items():
        other = modelled[kind]
        for key in sorted(objects.keys() | other.keys()):
            if objects.get(key) != other.get(key):
                lines.append(
                    f"{kind} {'.'.join(key)}\n"
                    f"    migrations: {objects.get(key)}\n"
                    f"    models:     {other.get(key)}"
                )
    return lines


def _alembic_diffs(engine: Engine, metadata: sa.MetaData) -> list[object]:
    """Compare a metadata with the database, as ``alembic check`` does.

    :param engine: The migrated database
    :param metadata: The metadata to compare
    :return: Alembic's list of differences, empty when they agree
    """
    with engine.connect() as connection:
        context = MigrationContext.configure(connection, opts=dict(COMPARE_OPTIONS))
        return list(compare_metadata(context, metadata))


def _copy_metadata() -> sa.MetaData:
    """Copy the application metadata so a test can mutate the copy.

    :return: A new metadata holding a copy of every table
    """
    copy = sa.MetaData(naming_convention=NAMING_CONVENTION)
    for table in Base.metadata.sorted_tables:
        table.to_metadata(copy)
    return copy


@pytest.fixture(scope="module")
def head_engine(postgres_url: str) -> Iterator[Engine]:
    """Yield an engine on a throwaway database migrated to head.

    Its own database rather than the session's ``migrated_url``, so no
    other test's leftovers can make the comparison pass or fail.

    :param postgres_url: The owner connection URL of the container
    :return: A context manager yielding the engine
    """
    with stage_at(postgres_url, "head") as engine:
        yield engine


@pytest.fixture(scope="module")
def migrated_catalogue(head_engine: Engine) -> Catalogue:
    """Read the migrated database's catalogue once for the module.

    :param head_engine: The database migrated to head
    :return: Its catalogue
    """
    return _catalogue(head_engine)


def test_alembic_check_finds_no_drift_at_head(head_engine: Engine) -> None:
    config = Config("alembic.ini")
    config.set_main_option("sqlalchemy.url", _url(head_engine))
    try:
        command.check(config)
    except AutogenerateDiffsDetected:
        diffs = "\n".join(
            f"  {diff}" for diff in _alembic_diffs(head_engine, Base.metadata)
        )
        pytest.fail(
            "app/db/models.py has drifted from the migrations, and an "
            "autogenerate would emit these operations. Describe each object "
            "in the models; the migration is the source of truth:\n" + diffs
        )


def test_the_models_build_the_schema_the_migrations_build(
    postgres_url: str, migrated_catalogue: Catalogue
) -> None:
    with _built_from(postgres_url, Base.metadata) as engine:
        modelled = _catalogue(engine)

    differences = _differences(migrated_catalogue, modelled)
    assert differences == [], (
        "app/db/models.py describes a different schema from the migrations:\n"
        + "\n".join(differences)
    )


def test_the_catalogue_is_not_vacuous(migrated_catalogue: Catalogue) -> None:
    # A query that matched nothing would compare two empty dicts and pass.
    # One object of each kind the drift was made of, named, proves each
    # query reads what it claims to.
    assert ("refresh_token", "revoked_at") in migrated_catalogue["column"]
    assert ("notification", "ix_notification_unread") in migrated_catalogue["index"]
    assert (
        "enrollment",
        "fk_enrollment_batch_id_batch",
    ) in migrated_catalogue["constraint"]
    assert ("ledger_entry_kind",) in migrated_catalogue["enum"]


