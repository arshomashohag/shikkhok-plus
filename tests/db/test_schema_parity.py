def test_alembic_reports_a_model_column_with_no_migration(
    head_engine: Engine,
) -> None:
    metadata = _copy_metadata()
    metadata.tables["refresh_token"].append_column(
        sa.Column("drift_probe", sa.Integer, nullable=True)
    )

    reported = [
        diff
        for diff in _alembic_diffs(head_engine, metadata)
        if isinstance(diff, tuple)
        and diff[0] == "add_column"
        and diff[3].name == "drift_probe"
    ]
    assert len(reported) == 1


def test_alembic_reports_a_migration_index_the_model_lacks(
    head_engine: Engine,
) -> None:
    metadata = _copy_metadata()
    table = metadata.tables["notification"]
    (unread,) = [
        index for index in table.indexes if index.name == "ix_notification_unread"
    ]
    table.indexes.discard(unread)

    reported = [
        diff
        for diff in _alembic_diffs(head_engine, metadata)
        if isinstance(diff, tuple)
        and diff[0] == "remove_index"
        and diff[1].name == "ix_notification_unread"
    ]
    assert len(reported) == 1


def test_the_catalogue_reports_what_alembic_cannot_see(
    postgres_url: str, migrated_catalogue: Catalogue
) -> None:
    # Three changes Alembic 1.20's comparison passed silently when this
    # gate was written: a partial index's predicate, a CHECK's
    # expression, an enum's labels.
    metadata = _copy_metadata()
    (unread,) = [
        index
        for index in metadata.tables["notification"].indexes
        if index.name == "ix_notification_unread"
    ]
    unread.dialect_options["postgresql"]["where"] = sa.text("read_at IS NOT NULL")
    (due_day,) = [
        constraint
        for constraint in metadata.tables["batch"].constraints
        if isinstance(constraint, sa.CheckConstraint)
        and "fee_due_day BETWEEN" in str(constraint.sqltext)
    ]
    due_day.sqltext = sa.text("fee_due_day BETWEEN 1 AND 28")
    metadata.tables["salary_line"].c.status.type = ENUM(
        "draft", "approved", "paid", name="salary_status", create_type=False
    )

    with _built_from(postgres_url, metadata) as engine:
        differences = _differences(migrated_catalogue, _catalogue(engine))

    reported = {line.split("\n", 1)[0] for line in differences}
    assert reported == {
        "index notification.ix_notification_unread",
        "constraint batch.ck_batch_ck_batch_fee_due_day",
        "enum salary_status",
    }
