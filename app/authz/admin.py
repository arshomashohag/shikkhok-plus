"""Who is a platform administrator: an allowlist of numbers and addresses.

**Configuration, not a column.** ``Account`` deliberately has no role
column [BR1.1], and an administrator flag would be the same stale-role
defect in a new place. The allowlist lives in the deployment's runtime
environment, so granting or revoking it is a deploy-time decision a
person makes, recorded where the other secrets are.

**Empty means nobody.** An unset or blank variable grants the lens to no
account, so a deployment that forgets it has no administration surface
rather than an open one.

**Phone numbers and email addresses, in one list** [0032]. The variable
kept its name, ``..._PHONES``, so no deployment's secret has to move: an
entry with an ``@`` is an email address, any other is a phone number.
An account is an administrator when either of its own -- verified --
identifiers is listed.
"""

from __future__ import annotations

import hmac
import ipaddress
import os
from typing import Final

from app.accounts.identifier import canonical_email
from app.accounts.phone import canonical_phone
from app.errors import ValidationError

__all__ = [
    "ADMIN_ALLOWED_CIDRS_ENV",
    "ADMIN_EDGE_HEADER",
    "ADMIN_EDGE_SECRET_ENV",
    "PLATFORM_ADMIN_PHONES_ENV",
    "admin_edge_ok",
    "admin_network_ok",
    "is_platform_admin",
    "platform_admins",
]

#: Comma-separated phone numbers and email addresses [0032]: numbers in
#: any spelling ``canonical_phone`` accepts, addresses in any case.
PLATFORM_ADMIN_PHONES_ENV: Final = "SHIKKHOKPLUS_PLATFORM_ADMIN_PHONES"


def platform_admins() -> frozenset[str]:
    """Read the allowlist, canonicalised.

    Read per call rather than at import, so a test or a restarted process
    sees the current value and nothing caches a revoked entry.

    :return: The canonical numbers and addresses, possibly empty
    :raises ValidationError: An entry is neither a Bangladeshi mobile
        number nor an email address; a typo must fail loudly rather than
        silently lock the admin out
    """
    raw = os.environ.get(PLATFORM_ADMIN_PHONES_ENV, "")
    admins: set[str] = set()
    for entry in raw.split(","):
        if not entry.strip():
            continue
        admins.add(canonical_email(entry) if "@" in entry else canonical_phone(entry))
    return frozenset(admins)


def is_platform_admin(phone: str | None, email: str | None = None) -> bool:
    """Report whether an account's number or address is on the allowlist.

    A malformed allowlist answers False for everyone rather than raising
    into a request: the misconfiguration is reported by
    :func:`platform_admins` wherever it is called directly.

    :param phone: The account's stored, canonical number, or None
    :param email: The account's stored, canonical address, or None
    :return: True only when one of them is allowlisted
    """
    try:
        admins = platform_admins()
    except ValidationError:
        return False
    return (phone is not None and phone in admins) or (
        email is not None and email in admins
    )


#: The header the admin CloudFront distribution adds to every request it
#: sends to the origin. A viewer cannot set it: CloudFront overwrites a
#: custom origin header of the same name, and the public API
#: distribution refuses ``/v1/admin*`` at the edge before any header is
#: forwarded.
ADMIN_EDGE_HEADER: Final = "X-Admin-Edge"

#: The value that header must carry, generated by Terraform and written
#: into the runtime environment by the deploy.
ADMIN_EDGE_SECRET_ENV: Final = "SHIKKHOKPLUS_ADMIN_EDGE_SECRET"  # noqa: S105  a variable name, not a secret

#: Comma-separated CIDRs an administrator may connect from, the same
#: list the admin distribution's edge function enforces.
ADMIN_ALLOWED_CIDRS_ENV: Final = "SHIKKHOKPLUS_ADMIN_ALLOWED_CIDRS"


def admin_edge_ok(presented: str | None) -> bool:
    """Report whether a request came through the admin distribution.

    **Unset means no request qualifies**: a deployment that forgets the
    secret has no reachable admin surface rather than an open one.

    :param presented: The ``X-Admin-Edge`` header, or None
    :return: True only for the configured secret, compared in constant time
    """
    expected = os.environ.get(ADMIN_EDGE_SECRET_ENV, "")
    if not expected or presented is None:
        return False
    return hmac.compare_digest(presented.encode(), expected.encode())


def admin_network_ok(address: str | None) -> bool:
    """Report whether a client address is on the admin allowlist.

    The second lock behind the edge function's: the edge refuses first,
    and this refuses anything that reached the origin some other way.
    **Empty or malformed means nobody**, for the same fail-closed reason.

    :param address: The verified client address, or None
    :return: True only for an address inside an allowed network
    """
    if not address:
        return False
    try:
        client = ipaddress.ip_address(address.strip())
        networks = [
            ipaddress.ip_network(entry.strip(), strict=False)
            for entry in os.environ.get(ADMIN_ALLOWED_CIDRS_ENV, "").split(",")
            if entry.strip()
        ]
    except ValueError:
        return False
    return any(client in network for network in networks)
