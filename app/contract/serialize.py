"""Canonical serialization of the OpenAPI document.

The schema-diff gate compares committed bytes against generated bytes, so
generation must be **deterministic across processes**. That is a security
requirement rather than an ergonomic one: a byte comparison over unstable
output produces false failures, and a gate that cries wolf is disabled by
whoever is holding the pager on a bad afternoon -- after which nothing is
checking the contract at all.

**``sort_keys`` alone is not sufficient, and this was measured rather than
assumed.** It orders object *keys*; it does not order a list *value*. An
OpenAPI ``required`` list built from a ``set`` keeps its hash ordering
straight through a fully canonical dump, and Python seeds hash
randomization once per process -- so such a document differs between an
in-process and a subprocess generation while two generations inside one
process agree. Sorting the order-insensitive lists is the half that
actually closes it.

**Only order-insensitive lists are sorted.** Sorting every list would
corrupt the parts of an OpenAPI document where order carries meaning:
``servers`` is tried in order, ``allOf`` composition order affects how a
reader merges subschemas, and ``parameters`` order is conventionally
preserved. The allowlist below is deliberately narrow.
"""

from __future__ import annotations

import json
from typing import Final

__all__ = ["ORDER_INSENSITIVE_KEYS", "canonical"]

#: Lists whose order carries no meaning, and which a ``set``-derived value
#: therefore makes non-deterministic. Narrow by design: anything not named
#: here keeps its order, because the cost of wrongly sorting an
#: order-SENSITIVE list is a corrupted contract rather than a flaky gate.
ORDER_INSENSITIVE_KEYS: Final[frozenset[str]] = frozenset(
    {
        "required",
        "enum",
        "tags",
        "security",
    }
)


def _sort_lists(node: object, key: str | None = None) -> object:
    """Recursively sort the order-insensitive lists in a document.

    :param node: The document node to normalise
    :param key: The mapping key this node was reached under, if any
    :return: The node with order-insensitive lists sorted
    """
    if isinstance(node, dict):
        return {
            child_key: _sort_lists(value, child_key)
            for child_key, value in node.items()
        }
    if isinstance(node, list):
        items = [_sort_lists(item) for item in node]
        if key in ORDER_INSENSITIVE_KEYS:
            strings = [item for item in items if isinstance(item, str)]
            # Only sort when EVERY element is a string. A list of objects
            # has no total order, and inventing one by key would reorder
            # the document on an unrelated change.
            if len(strings) == len(items):
                return sorted(strings)
        return items
    return node


def canonical(document: dict[str, object]) -> str:
    """Serialize a document deterministically across processes.

    :param document: The generated OpenAPI document
    :return: The canonical serialization, newline-terminated
    """
    normalised = _sort_lists(document)
    return (
        json.dumps(
            normalised,
            sort_keys=True,
            separators=(",", ": "),
            ensure_ascii=False,
            indent=2,
        )
        + "\n"
    )
